// Числовые настройки, которые раньше были константами в коде.
//
// Все они не «магические числа ради читаемости», а значения, у которых
// на разных инстансах разумно разное: размер группы, длина сообщения,
// минимальная длина пароля, сколько звонить до «пропущенного».
//
// Читаются один раз при старте — как и остальной конфиг, изменения
// требуют рестарта сервера.

/**
 * Целое из окружения с нижней границей.
 *
 * Мусор и значения ниже min молча откатываются на дефолт: опечатка в
 * .env не должна, например, разрешить пароль из одного символа или
 * запретить сообщения длиннее нуля.
 */
function num(name, fallback, min = 1) {
  const n = Number(process.env[name]);
  if (!Number.isFinite(n)) return fallback;
  const v = Math.floor(n);
  return v >= min ? v : fallback;
}

/** Максимальная длина текста сообщения (символов). */
export const MESSAGE_MAX_CHARS = num('MESSAGE_MAX_CHARS', 4000, 1);

/** Сколько участников влезает в группу, включая владельца. */
export const MAX_GROUP_MEMBERS = num('MAX_GROUP_MEMBERS', 10, 2);

/** Максимальная длина названия группы. */
export const GROUP_NAME_MAX = num('GROUP_NAME_MAX', 64, 1);

/**
 * Сколько файлов можно приложить к одному сообщению.
 *
 * Это отдельный от MAX_UPLOAD_MB рычаг: тот режет размер КАЖДОГО файла,
 * а этот — их количество. Вместе они и задают потолок одного запроса.
 */
export const MAX_FILES_PER_MESSAGE = num('MAX_FILES_PER_MESSAGE', 10, 1);

/**
 * Минимальная длина пароля. Поднимать имеет смысл на публичном
 * инстансе; опускать ниже 6 нельзя — это уже не «настройка», а дыра.
 */
export const MIN_PASSWORD_LENGTH = num('MIN_PASSWORD_LENGTH', 6, 6);

/** Сколько звоним, прежде чем считать вызов пропущенным. */
export const CALL_RING_TIMEOUT_MS = num('CALL_RING_TIMEOUT_SEC', 30, 5) * 1000;

/**
 * Сколько держим оборвавшийся звонок «живым», чтобы его можно было
 * подхватить после переподключения.
 */
export const CALL_RECONNECT_MS = num('CALL_RECONNECT_SEC', 300, 10) * 1000;
